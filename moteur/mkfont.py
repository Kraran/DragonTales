P=100
def draw(rows,above=None,below=None):
    pen=TTGlyphPen(None)
    def rect(x,y,w):
        pen.moveTo((x,y));pen.lineTo((x,y+P));pen.lineTo((x+w,y+P));pen.lineTo((x+w,y));pen.closePath()
    def line(r,y):
        c=0
        while c<5:
            if r[c]=='#':
                e=c
                while e<5 and r[e]=='#': e+=1
                rect(P+c*P,y,(e-c)*P); c=e
            else: c+=1
    for i,r in enumerate(rows): line(r,(6-i)*P)
    if above:
        for i,r in enumerate(above): line(r,(8-i)*P)
    if below:
        for i,r in enumerate(below): line(r,(-1-i)*P)
    return pen.glyph()
glyphs={'.notdef':draw(['#####','#...#','#...#','#...#','#...#','#...#','#####'])}
cmap={}
def add(ch,g):
    name='u%04X'%ord(ch); glyphs[name]=g; cmap[ord(ch)]=name; return name
for ch,rows in G.items(): add(ch,draw(rows))
for ch,(b,a) in ACCENTED.items(): add(ch,draw(G[b],above=ACC[a]))
add('Ç',draw(G['C'],below=['..#..','.#...']))
# minuscules et apostrophe typographique : renvoyees vers les memes dessins
for o in range(ord('a'),ord('z')+1): cmap[o]=cmap[o-32]
for a,b in (('à','À'),('â','Â'),('ç','Ç'),('è','È'),('é','É'),('ê','Ê'),('ë','Ë'),('î','Î'),('ï','Ï'),('ô','Ô'),('ù','Ù'),('û','Û'),('ü','Ü'),('œ','Œ'),('’',"'"),(' ',' ')): cmap[ord(a)]=cmap[ord(b)]
order=list(glyphs.keys())
fb=FontBuilder(1000,isTTF=True)
fb.setupGlyphOrder(order); fb.setupCharacterMap(cmap); fb.setupGlyf(glyphs)
def lsb(g):
    c=getattr(g,'coordinates',None)
    return min(x for x,y in c) if c is not None and len(c) else 0
fb.setupHorizontalMetrics({n:(800,lsb(glyphs[n])) for n in order})
fb.setupHorizontalHeader(ascent=1000,descent=-200)
