const STOP=new Set('LE LA LES L UN UNE DES DU DE D AU AUX A SUR DANS VERS EN AVEC ET MON MA MES CE CET CETTE CES PAR POUR Y'.split(' '));
const LIVING=new Set(['COYOTE','SNAKE','CROW','LIZARD','BEAST']);
const DIRS={O:'WEST',OUEST:'WEST',N:'NORTH',NORD:'NORTH',E:'EAST',EST:'EAST',S:'SOUTH',SUD:'SOUTH',H:'UP',HAUT:'UP',B:'DOWN',BAS:'DOWN'};
function norm(s){
  return s.toUpperCase().replace(/Œ/g,'OE').replace(/Æ/g,'AE').normalize('NFD').replace(/[̀-ͯ]/g,'')
          .replace(/['’`\-]/g,' ').replace(/[^A-Z0-9 ?!]/g,' ').replace(/\s+/g,' ').trim();
}
function frToEn(line){
  const n=norm(line); if(!n) return '';
  let t=n.split(' ');
  while(t.length>1 && ['JE','ME','SE','M','S','TE','T'].includes(t[0])) t.shift();
  if(t.length===1 && DIRS[t[0]]) return 'GO '+DIRS[t[0]];
  const w=t[0]; let verb=VERBS[w];
  if(!verb) return n;                       // pas du français connu : transmis tel quel (anglais accepté)
  const rest=t.slice(1).filter(x=>!STOP.has(x));
  let noun=null;
  for(const x of rest){ if(NOUNS[x]){ noun=NOUNS[x]; break; } }
  if(!noun && rest.length) noun=rest[rest.length-1];
  if((w==='MONTER'||w==='MONTE') && !noun) noun='UP';
  if((w==='DESCENDRE'||w==='DESCENDS') && !noun) noun='DOWN';
  if((w==='PLONGER'||w==='PLONGE')){ if(!noun) noun='DOWN'; else if(noun!=='DOWN'&&noun!=='UP') verb='DIP'; }
  if(verb==='PULL' && (!noun || LIVING.has(noun))) verb='SHOOT';
  if(verb==='INV'||verb==='CSAVE'||verb==='CLOAD') return verb;
  return noun?verb+' '+noun:verb;
}
